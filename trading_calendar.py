# -*- coding: utf-8 -*-
"""
交易日判断。

为什么需要它：
    GitHub Actions 的定时任务只认 cron，没法表达「只在交易日跑」。
    如果不过滤，周末和法定假日也会照跑，结果是：
      1) 白烧 Actions 额度；
      2) 每次生成一份和上次一模一样的数据，产生无意义的部署。

两层判断（先便宜后昂贵）：
    第一层 is_trading_day()：纯本地计算 —— 排除周末 + 查法定节假日表。
        零网络开销，能挡掉绝大多数无效运行。
    第二层 has_fresh_data()：看抓回来的行情是不是今天的。
        兜底用 —— 应对临时休市、交易所异常等「表里没写但确实没开市」的情况。

节假日表需要每年更新（国务院一般在上一年 11-12 月公布次年安排）。
表里没有的年份会退化成「只判断周末」，不会报错，只是可能多跑几次。
"""

from datetime import date, datetime, timedelta

# ---------------------------------------------------------------------------
# 中国法定节假日休市表
#
# 数据来源：国务院办公厅《关于2026年部分节假日安排的通知》
#           （国办发明电〔2025〕7号，2025-11-04 发布）
#
# 只列「落在工作日上的休市日」—— 周末本来就休市，不用重复列。
# 例如 2026 清明放假 4/4(周六)-4/6(周一)，只有 4/6 是工作日、需要列。
#
# 期货交易所休市安排与国务院放假基本一致，按此表判断足够准确。
# ---------------------------------------------------------------------------
HOLIDAYS = {
    # ---- 2026 年（官方通知，已核对）----
    "2026-01-01", "2026-01-02",                      # 元旦
    "2026-02-16", "2026-02-17", "2026-02-18",        # 春节（放假 2/15-2/23）
    "2026-02-19", "2026-02-20", "2026-02-23",        #   其中 2/15、2/21、2/22 是周末
    "2026-04-06",                                    # 清明（放假 4/4-4/6，仅 4/6 是工作日）
    "2026-05-01", "2026-05-04", "2026-05-05",        # 劳动节（放假 5/1-5/5，5/2、5/3 是周末）
    "2026-06-19",                                    # 端午（放假 6/19-6/21，后两天是周末）
    "2026-09-25",                                    # 中秋（放假 9/25-9/27，后两天是周末）
    "2026-10-01", "2026-10-02", "2026-10-05",        # 国庆（放假 10/1-10/7，10/3、10/4 是周末）
    "2026-10-06", "2026-10-07",

    # ---- 2027 年（官方尚未公布，按近年惯例预估，公布后请核对替换）----
    "2027-01-01",                                    # 元旦
    "2027-02-05", "2027-02-08", "2027-02-09",        # 春节（预估）
    "2027-02-10", "2027-02-11",
    "2027-04-05",                                    # 清明（预估）
    "2027-05-03", "2027-05-04", "2027-05-05",        # 劳动节（预估）
    "2027-06-09",                                    # 端午（预估）
    "2027-10-01", "2027-10-04", "2027-10-05",        # 国庆（预估）
    "2027-10-06", "2027-10-07",
}

# 节假日表覆盖到的年份（用来提示用户该更新了）
KNOWN_YEARS = {int(d[:4]) for d in HOLIDAYS}


def is_weekend(d):
    """周六 / 周日。"""
    return d.weekday() >= 5


def is_holiday(d):
    """法定节假日休市。"""
    return d.strftime("%Y-%m-%d") in HOLIDAYS


def is_trading_day(d=None):
    """
    判断某天是否可能是交易日（本地判断，不联网）。

    返回 (bool, reason)：
        reason 用于日志说明为什么跳过，便于排查。
    """
    if d is None:
        d = date.today()

    if is_weekend(d):
        names = ("周一", "周二", "周三", "周四", "周五", "周六", "周日")
        return False, f"{d} 是{names[d.weekday()]}（周末休市）"

    if is_holiday(d):
        return False, f"{d} 是法定节假日（休市）"

    # 表里没有这个年份时，只能退化成「只判断周末」——
    # 不阻断运行，只提示一下，避免用户以为判断生效了其实没数据。
    if d.year not in KNOWN_YEARS:
        return True, (f"{d} 是工作日，但节假日表未覆盖 {d.year} 年"
                      f"（请更新 trading_calendar.HOLIDAYS）")

    return True, f"{d} 是交易日"


def has_fresh_data(quote, today=None):
    """
    兜底判断：抓回来的行情快照是不是「今天」的。

    用途：本地表判断是交易日、但实际没开市（临时休市等）时，
    避免把一份陈旧数据当成新的发布出去。
    注意：仅用于「跳过」判断，字段缺失时返回 True（不阻断），
    免得因为接口偶发缺字段就把正常交易日也跳过了。
    """
    if not quote:
        return True
    qd = (quote.get("date") or "").strip()[:10]
    if not qd:
        return True
    if today is None:
        today = date.today()
    return qd == today.strftime("%Y-%m-%d")


def next_trading_day(d, include_self=False):
    """返回 d 之后（含 d）的第一个交易日。"""
    cur = d if include_self else d + timedelta(days=1)
    for _ in range(30):          # 最长连休不会超过 30 天，兜底防死循环
        if not is_weekend(cur) and not is_holiday(cur):
            return cur
        cur += timedelta(days=1)
    return cur


def session_trading_check(now=None, night_start_hour=20):
    """
    按「当前时刻属于哪个交易时段」来判断要不要跑。

    为什么要分时段（重要）：
        夜盘 21:00 开盘，成交的是「下一个交易日」的行情。
        例如周五 21:00 的夜盘，K 线时间戳属于下周一（或下个交易日）。

    夜盘开不开，取决于**明天（下一个自然日）是不是交易日**：
        - 周末前的周五夜盘：明天是周六 —— 但期货夜盘周五是开的
          （周五夜盘对应下周一），所以周末要特殊处理。
        - 长假前最后一个交易日的夜盘：**不开**。
          例如 9/30（周三）晚上是国庆前最后一天，10/1 起休市，
          当晚没有夜盘；再如春节前最后一天晚上同样不开。

    准确规则（按交易所实际口径）：
        夜盘是否开市 = 「下一个交易日」距离今天不超过 3 个自然日。
        推导：
          - 周五夜盘 -> 下周一，间隔 3 天 -> 开
          - 周四夜盘 -> 周五，   间隔 1 天 -> 开
          - 9/30 夜盘 -> 10/8，  间隔 8 天 -> 不开（长假）
          - 2/13 夜盘 -> 2/24，  间隔 11 天 -> 不开（春节）
        3 天这个阈值正好把「跨周末」和「跨长假」区分开。

    返回 (should_run, reason)
    """
    from datetime import datetime as _dt

    if now is None:
        now = _dt.now()

    d = now.date()
    is_night = now.hour >= night_start_hour

    if not is_night:
        # 日盘：直接看当天是不是交易日
        return is_trading_day(d)

    # ---- 夜盘 ----
    nxt = next_trading_day(d)
    gap = (nxt - d).days
    # 间隔超过 3 个自然日 = 中间夹了长假，当晚没有夜盘
    if gap > 3:
        return False, (f"夜盘时段，但下一个交易日是 {nxt}（距今 {gap} 天，"
                       f"中间为长假，当晚无夜盘）")
    return True, f"夜盘时段，对应交易日 {nxt}"
